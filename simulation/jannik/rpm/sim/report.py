"""Compare all strategies against the acceptance criteria and write a report.

The report (Markdown + two PNG plots) is the simulation team's deliverable
for the question "which motion averages gravity out best on our machine?".
"""

from dataclasses import dataclass
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # headless: CI and terminals without a display

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from rpm.core.metrics import N_CELLS  # noqa: E402
from rpm.core.strategies import STRATEGIES  # noqa: E402
from rpm.sim.simulate import ServoPlant, SimResult, error_envelope, run  # noqa: E402

RESIDUAL_LIMIT_G = 0.01
COVERAGE_LIMITS = (0.5, 2.5)


@dataclass
class StrategySummary:
    name: str
    runs: list[SimResult]

    @property
    def residuals(self) -> np.ndarray:
        return np.array([r.residual_gravity for r in self.runs])

    @property
    def coverage(self) -> tuple[float, float]:
        return (
            min(r.coverage_range[0] for r in self.runs),
            max(r.coverage_range[1] for r in self.runs),
        )

    @property
    def passes(self) -> bool:
        lo, hi = self.coverage
        return bool(
            self.residuals.max() < RESIDUAL_LIMIT_G
            and COVERAGE_LIMITS[0] <= lo
            and hi <= COVERAGE_LIMITS[1]
        )


def compare(duration_s: float = 600.0, seeds: int = 5) -> list[StrategySummary]:
    """Run every strategy on the nominal model and every envelope corner."""
    scenarios: list[tuple[ServoPlant, ServoPlant]] = [(ServoPlant(), ServoPlant())]
    scenarios += error_envelope()
    summaries = []
    for name in sorted(STRATEGIES):
        runs = [
            run(name, duration_s, seed=seed, outer_plant=po, inner_plant=pi)
            for po, pi in scenarios
            for seed in range(1, seeds + 1)
        ]
        summaries.append(StrategySummary(name, runs))
    return summaries


def _plot_residual(summaries: list[StrategySummary], path: Path) -> None:
    fig, ax = plt.subplots(figsize=(8, 4.5))
    for s in summaries:
        curves = np.array([r.residual_g for r in s.runs])
        t_min = s.runs[0].time_s / 60.0
        (line,) = ax.plot(t_min, np.median(curves, axis=0), label=s.name)
        ax.fill_between(
            t_min, curves.min(axis=0), curves.max(axis=0), color=line.get_color(), alpha=0.15
        )
    ax.axhline(RESIDUAL_LIMIT_G, color="black", linestyle="--", linewidth=1, label="limit")
    ax.set_yscale("log")
    ax.set_ylim(1e-4, 1.0)
    ax.set_xlabel("time [min]")
    ax.set_ylabel("|time-averaged gravity| [g]")
    ax.set_title("Residual gravity (median, band = best..worst run)")
    ax.legend()
    ax.grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def _plot_coverage(summaries: list[StrategySummary], path: Path) -> None:
    fig, ax = plt.subplots(figsize=(8, 4.5))
    width = 0.8 / len(summaries)
    cells = np.arange(N_CELLS)
    for i, s in enumerate(summaries):
        ratios = np.mean([r.true_stats.coverage_ratios() for r in s.runs], axis=0)
        ax.bar(cells + i * width, ratios, width, label=s.name)
    for limit in COVERAGE_LIMITS:
        ax.axhline(limit, color="black", linestyle="--", linewidth=1)
    ax.axhline(1.0, color="grey", linewidth=1)
    ax.set_xticks(cells + 0.4 - width / 2, [str(c) for c in cells])
    ax.set_xlabel("direction cell (icosahedron face)")
    ax.set_ylabel("time share / uniform share")
    ax.set_title("Coverage of gravity directions (mean over runs)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def write_report(summaries: list[StrategySummary], out_dir: Path, duration_s: float) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    _plot_residual(summaries, out_dir / "residual.png")
    _plot_coverage(summaries, out_dir / "coverage.png")
    runs = len(summaries[0].runs)
    lines = [
        "# Strategy comparison",
        "",
        f"Generated by `rpm-sim compare`: {duration_s / 60:.0f} min simulated per run, "
        f"{runs} runs per strategy (nominal servo model plus the four corners of the error "
        "envelope: +-20 % speed, +-15 us dead-band shift, 3 % noise, several seeds).",
        "",
        f"Criteria (docs/api.md): residual gravity < {RESIDUAL_LIMIT_G} g in *every* run, "
        f"coverage ratio of every cell within [{COVERAGE_LIMITS[0]}, {COVERAGE_LIMITS[1]}].",
        "",
        "| Strategy | median residual [g] | worst residual [g] | coverage min..max | pass |",
        "|---|---:|---:|---|:---:|",
    ]
    for s in summaries:
        lo, hi = s.coverage
        lines.append(
            f"| `{s.name}` | {np.median(s.residuals):.4f} | {s.residuals.max():.4f} | "
            f"{lo:.2f}..{hi:.2f} | {'yes' if s.passes else 'no'} |"
        )
    lines += ["", "![Residual gravity](residual.png)", "", "![Coverage](coverage.png)", ""]
    path = out_dir / "README.md"
    path.write_text("\n".join(lines))
    return path
